@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly injector = inject(Injector);
  readonly lang = signal<'es' | 'en'>(this.stored() ?? 'es');

  constructor() {
    document.documentElement.lang = this.lang();
  }

  t(spanish: string): string {
    return this.lang() === 'en' ? (EN[spanish] ?? spanish) : spanish;
  }

  live(message?: string | null): string {
    if (!message) return '';
    if (this.lang() === 'en') return EN[message] ?? message;
    return REVERSE[message] ?? message;
  }

  label(value?: string | null): string {
    if (!value) return '';
    const pair = LABELS[value];
    if (!pair) return value;
    return this.lang() === 'en' ? pair[1] : pair[0];
  }

  date(value?: string | null): string {
    if (!value) return '';
    const locale = this.lang() === 'en' ? 'en-US' : 'es-DO';
    return new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', year: 'numeric' }).format(new Date(value));
  }

  money(amount: number, currency = 'DOP'): string {
    const locale = this.lang() === 'en' ? 'en-US' : 'es-DO';
    return new Intl.NumberFormat(locale, { style: 'currency', currency, maximumFractionDigits: 0 }).format(amount);
  }

  salary(job: { salaryMin?: number | null; salaryMax?: number | null; salaryCurrency?: string | null; salaryPeriod?: string | null; salaryNegotiable?: boolean }): string {
    const currency = job.salaryCurrency || 'DOP';
    const period = job.salaryPeriod ? this.label(job.salaryPeriod) : '';
    let base = '';
    if (job.salaryMin != null && job.salaryMax != null) base = `${this.money(job.salaryMin, currency)} – ${this.money(job.salaryMax, currency)}`;
    else if (job.salaryMin != null) base = `${this.t('Desde')} ${this.money(job.salaryMin, currency)}`;
    else if (job.salaryMax != null) base = `${this.t('Hasta')} ${this.money(job.salaryMax, currency)}`;
    if (!base) return job.salaryNegotiable ? this.t('Salario negociable frase') : this.t('Salario no indicado');
    const suffix = period ? ` / ${period}` : '';
    return job.salaryNegotiable ? `${base}${suffix} · ${this.t('negociable')}` : `${base}${suffix}`;
  }

  place(job: { municipality?: string | null; province?: string | null; locationLabel?: string | null; countryName?: string | null; workMode?: string }): string {
    if (job.locationLabel) return job.locationLabel;
    if (job.municipality && job.province) return `${job.municipality}, ${job.province}`;
    if (job.province) return job.province;
    if (job.workMode === 'REMOTE') return job.countryName ? `${this.t('Remoto')} · ${job.countryName}` : this.t('Remoto');
    return job.countryName || this.t('República Dominicana');
  }

  apiError(error: unknown): string {
    const body = (error as { error?: { message?: string; errors?: { message: string }[] } })?.error;
    if (body?.errors?.length) return body.errors.map((item) => item.message).join(' ');
    return body?.message || this.t('No se pudo completar la acción.');
  }

  use(lang: 'es' | 'en'): void {
    this.lang.set(lang);
    localStorage.setItem('empleord.lang', lang);
    document.documentElement.lang = lang;
    void this.persist(lang);
  }

  restore(userLocale?: string | null): void {
    const saved = this.stored();
    if (saved) {
      this.lang.set(saved);
      document.documentElement.lang = saved;
      if (userLocale && userLocale !== saved) void this.persist(saved);
      return;
    }
    if (userLocale === 'en' || userLocale === 'es') {
      this.lang.set(userLocale);
      localStorage.setItem('empleord.lang', userLocale);
      document.documentElement.lang = userLocale;
    }
  }

  private async persist(locale: 'es' | 'en'): Promise<void> {
    const auth = this.injector.get(AuthService);
    if (!auth.token()) return;
    const http = this.injector.get(HttpClient);
    await firstValueFrom(http.patch('/api/auth/locale', { locale })).catch(() => undefined);
  }

  private stored(): 'es' | 'en' | null {
    const value = localStorage.getItem('empleord.lang');
    return value === 'en' || value === 'es' ? value : null;
  }
}
