CREATE TABLE roles (
    id SMALLINT PRIMARY KEY,
    name VARCHAR(32) NOT NULL UNIQUE
);

CREATE TABLE users (
    id UUID PRIMARY KEY,
    role_id SMALLINT NOT NULL REFERENCES roles (id),
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    phone VARCHAR(30),
    status VARCHAR(32) NOT NULL,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    email_verification_token_hash VARCHAR(64),
    email_verification_expires_at TIMESTAMPTZ,
    password_reset_token_hash VARCHAR(64),
    password_reset_expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX uq_users_email_active ON users (email) WHERE deleted_at IS NULL;
CREATE INDEX idx_users_role ON users (role_id);
CREATE INDEX idx_users_status ON users (status);

CREATE TABLE refresh_tokens (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users (id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE countries (
    code VARCHAR(2) PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE provinces (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    code VARCHAR(8) NOT NULL UNIQUE
);

CREATE TABLE municipalities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    province_id INTEGER NOT NULL REFERENCES provinces (id),
    name VARCHAR(120) NOT NULL,
    CONSTRAINT uq_municipality_province UNIQUE (province_id, name)
);

CREATE INDEX idx_municipalities_province ON municipalities (province_id);

CREATE TABLE job_categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    slug VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE skills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE candidate_profiles (
    user_id UUID PRIMARY KEY REFERENCES users (id),
    headline VARCHAR(160),
    summary TEXT,
    province_id INTEGER REFERENCES provinces (id),
    municipality_id INTEGER REFERENCES municipalities (id),
    linkedin_url VARCHAR(255),
    portfolio_url VARCHAR(255),
    salary_min NUMERIC(12, 2),
    salary_max NUMERIC(12, 2),
    salary_currency VARCHAR(3) NOT NULL DEFAULT 'DOP',
    salary_period VARCHAR(20),
    open_to_work BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_candidate_salary CHECK (salary_min IS NULL OR salary_max IS NULL OR salary_min <= salary_max)
);

CREATE TABLE resumes (
    id UUID PRIMARY KEY,
    candidate_id UUID NOT NULL REFERENCES candidate_profiles (user_id),
    original_filename VARCHAR(255) NOT NULL,
    storage_key VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    primary_resume BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_resumes_candidate ON resumes (candidate_id);

CREATE TABLE work_experiences (
    id UUID PRIMARY KEY,
    candidate_id UUID NOT NULL REFERENCES candidate_profiles (user_id) ON DELETE CASCADE,
    job_title VARCHAR(160) NOT NULL,
    company_name VARCHAR(160) NOT NULL,
    location VARCHAR(160),
    start_date DATE NOT NULL,
    end_date DATE,
    current_job BOOLEAN NOT NULL DEFAULT FALSE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_experience_candidate ON work_experiences (candidate_id);

CREATE TABLE educations (
    id UUID PRIMARY KEY,
    candidate_id UUID NOT NULL REFERENCES candidate_profiles (user_id) ON DELETE CASCADE,
    institution VARCHAR(180) NOT NULL,
    degree VARCHAR(160) NOT NULL,
    field_of_study VARCHAR(160),
    start_year INTEGER,
    end_year INTEGER,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_education_candidate ON educations (candidate_id);

CREATE TABLE certifications (
    id UUID PRIMARY KEY,
    candidate_id UUID NOT NULL REFERENCES candidate_profiles (user_id) ON DELETE CASCADE,
    name VARCHAR(180) NOT NULL,
    issuer VARCHAR(180),
    issue_year INTEGER,
    credential_url VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_certifications_candidate ON certifications (candidate_id);

CREATE TABLE candidate_skills (
    candidate_id UUID NOT NULL REFERENCES candidate_profiles (user_id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES skills (id),
    PRIMARY KEY (candidate_id, skill_id)
);

CREATE TABLE candidate_languages (
    id UUID PRIMARY KEY,
    candidate_id UUID NOT NULL REFERENCES candidate_profiles (user_id) ON DELETE CASCADE,
    language VARCHAR(60) NOT NULL,
    proficiency VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_languages_candidate ON candidate_languages (candidate_id);

CREATE TABLE employer_profiles (
    user_id UUID PRIMARY KEY REFERENCES users (id),
    job_title VARCHAR(120),
    phone VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE companies (
    id UUID PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    slug VARCHAR(180) NOT NULL UNIQUE,
    description TEXT,
    website VARCHAR(255),
    logo_storage_key VARCHAR(255),
    industry VARCHAR(120),
    province_id INTEGER REFERENCES provinces (id),
    municipality_id INTEGER REFERENCES municipalities (id),
    country_code VARCHAR(2) NOT NULL DEFAULT 'DO' REFERENCES countries (code),
    verification_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    status VARCHAR(32) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ
);

CREATE INDEX idx_companies_status ON companies (status);

CREATE TABLE company_verifications (
    id UUID PRIMARY KEY,
    company_id UUID NOT NULL REFERENCES companies (id),
    status VARCHAR(32) NOT NULL,
    notes TEXT,
    reviewed_by UUID REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ
);

CREATE INDEX idx_company_verifications_company ON company_verifications (company_id);

CREATE TABLE company_members (
    id UUID PRIMARY KEY,
    company_id UUID NOT NULL REFERENCES companies (id),
    user_id UUID NOT NULL UNIQUE REFERENCES users (id),
    member_role VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_company_member UNIQUE (company_id, user_id)
);

CREATE INDEX idx_company_members_company ON company_members (company_id);

CREATE TABLE jobs (
    id UUID PRIMARY KEY,
    company_id UUID NOT NULL REFERENCES companies (id),
    created_by UUID NOT NULL REFERENCES users (id),
    title VARCHAR(180) NOT NULL,
    slug VARCHAR(220) NOT NULL UNIQUE,
    description TEXT NOT NULL,
    requirements TEXT,
    responsibilities TEXT,
    category_id INTEGER NOT NULL REFERENCES job_categories (id),
    contract_type VARCHAR(32) NOT NULL,
    work_mode VARCHAR(32) NOT NULL,
    work_schedule VARCHAR(32) NOT NULL,
    experience_level VARCHAR(32) NOT NULL,
    province_id INTEGER REFERENCES provinces (id),
    municipality_id INTEGER REFERENCES municipalities (id),
    country_code VARCHAR(2) NOT NULL DEFAULT 'DO' REFERENCES countries (code),
    location_label VARCHAR(160),
    remote_scope VARCHAR(32) NOT NULL,
    geographic_restriction VARCHAR(255),
    salary_min NUMERIC(12, 2),
    salary_max NUMERIC(12, 2),
    salary_currency VARCHAR(3) NOT NULL DEFAULT 'DOP',
    salary_period VARCHAR(20),
    salary_negotiable BOOLEAN NOT NULL DEFAULT FALSE,
    accepts_no_experience BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(32) NOT NULL,
    published_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    view_count BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT chk_job_salary CHECK (salary_min IS NULL OR salary_max IS NULL OR salary_min <= salary_max)
);

CREATE INDEX idx_jobs_public ON jobs (status, published_at DESC);
CREATE INDEX idx_jobs_company ON jobs (company_id);
CREATE INDEX idx_jobs_category ON jobs (category_id);
CREATE INDEX idx_jobs_province ON jobs (province_id);
CREATE INDEX idx_jobs_expires ON jobs (expires_at);

CREATE TABLE job_skills (
    job_id UUID NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES skills (id),
    PRIMARY KEY (job_id, skill_id)
);

CREATE TABLE job_applications (
    id UUID PRIMARY KEY,
    job_id UUID NOT NULL REFERENCES jobs (id),
    candidate_id UUID NOT NULL REFERENCES candidate_profiles (user_id),
    resume_id UUID REFERENCES resumes (id),
    cover_letter TEXT,
    status VARCHAR(32) NOT NULL,
    internal_note TEXT,
    favorite BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_application_job_candidate UNIQUE (job_id, candidate_id)
);

CREATE INDEX idx_applications_candidate ON job_applications (candidate_id, created_at DESC);
CREATE INDEX idx_applications_job_status ON job_applications (job_id, status);

CREATE TABLE saved_jobs (
    candidate_id UUID NOT NULL REFERENCES candidate_profiles (user_id) ON DELETE CASCADE,
    job_id UUID NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (candidate_id, job_id)
);

CREATE TABLE job_alerts (
    id UUID PRIMARY KEY,
    candidate_id UUID NOT NULL REFERENCES candidate_profiles (user_id) ON DELETE CASCADE,
    keyword VARCHAR(160),
    province_id INTEGER REFERENCES provinces (id),
    category_id INTEGER REFERENCES job_categories (id),
    work_mode VARCHAR(32),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_job_alerts_candidate ON job_alerts (candidate_id);

CREATE TABLE notifications (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users (id),
    type VARCHAR(50) NOT NULL,
    title VARCHAR(180) NOT NULL,
    body TEXT NOT NULL,
    link VARCHAR(255),
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_notifications_user ON notifications (user_id, created_at DESC);

CREATE TABLE reports (
    id UUID PRIMARY KEY,
    reporter_id UUID REFERENCES users (id),
    reporter_email VARCHAR(255),
    target_type VARCHAR(32) NOT NULL,
    target_id UUID NOT NULL,
    reason VARCHAR(80) NOT NULL,
    details TEXT,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_reports_status ON reports (status, created_at DESC);

CREATE TABLE subscription_plans (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL,
    description TEXT,
    price_amount NUMERIC(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'DOP',
    billing_period VARCHAR(20) NOT NULL,
    max_active_jobs INTEGER NOT NULL,
    featured_credits INTEGER NOT NULL DEFAULT 0,
    candidate_filters BOOLEAN NOT NULL DEFAULT FALSE,
    advanced_stats BOOLEAN NOT NULL DEFAULT FALSE,
    premium_profile BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE company_subscriptions (
    id UUID PRIMARY KEY,
    company_id UUID NOT NULL UNIQUE REFERENCES companies (id),
    plan_id INTEGER NOT NULL REFERENCES subscription_plans (id),
    status VARCHAR(32) NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE featured_jobs (
    id UUID PRIMARY KEY,
    job_id UUID NOT NULL REFERENCES jobs (id),
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    created_by UUID REFERENCES users (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_featured_jobs_window ON featured_jobs (job_id, starts_at, ends_at);

CREATE TABLE audit_logs (
    id UUID PRIMARY KEY,
    actor_id UUID,
    action VARCHAR(80) NOT NULL,
    entity_type VARCHAR(80) NOT NULL,
    entity_id VARCHAR(64),
    metadata TEXT,
    ip_address VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_audit_logs_created ON audit_logs (created_at DESC);
CREATE INDEX idx_audit_logs_entity ON audit_logs (entity_type, entity_id);
